[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$project = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$basePath = Join-Path $PSScriptRoot 'runtime-base.js'
$widgetPath = Join-Path $PSScriptRoot 'widget-host.js'
$controlsPath = Join-Path $project 'widget-host/capture-controls.js'
$indicatorPath = Join-Path $project 'widget-host/capture-indicator.js'
$outputPath = Join-Path $PSScriptRoot 'runtime-hook.js'
$sourceThemeJar = '/data/local/tmp/watchface-theme/theme.jar'
$runtimeThemeJar = '/data/local/tmp/watchworkshop-runtime/theme.jar'

function Read-Normalized([string]$Path) {
    $text = [IO.File]::ReadAllText($Path)
    $text = $text.Replace("`r`n", "`n").Replace("`r", "`n")
    return $text.TrimEnd("`n") + "`n"
}

function Count-Text([string]$Text, [string]$Needle) {
    return ([regex]::Matches($Text, [regex]::Escape($Needle))).Count
}

function Require-Once([string]$Text, [string]$Needle, [string]$Label) {
    $count = Count-Text $Text $Needle
    if ($count -ne 1) {
        throw "$Label must appear exactly once; found $count"
    }
}

function Get-Sha256([string]$Text) {
    $sha = [Security.Cryptography.SHA256]::Create()
    try {
        $bytes = [Text.Encoding]::UTF8.GetBytes($Text)
        return ([BitConverter]::ToString($sha.ComputeHash($bytes))).Replace('-', '').ToLowerInvariant()
    }
    finally {
        $sha.Dispose()
    }
}

function Test-SameBytes([byte[]]$Left, [byte[]]$Right) {
    if ($Left.Length -ne $Right.Length) { return $false }
    for ($i = 0; $i -lt $Left.Length; $i++) {
        if ($Left[$i] -ne $Right[$i]) { return $false }
    }
    return $true
}

$base = Read-Normalized $basePath
$widget = Read-Normalized $widgetPath
$controls = Read-Normalized $controlsPath
$indicator = Read-Normalized $indicatorPath

$pathCount = Count-Text $controls $sourceThemeJar
if ($pathCount -ne 1) {
    throw "capture-controls.js must reference $sourceThemeJar exactly once; found $pathCount"
}
$controls = $controls.Replace($sourceThemeJar, $runtimeThemeJar)

# The shared capture module also carries a compatibility wrapper for v11's direct
# restoreTiles/NFC path. This runtime does not install that shared block, so omit
# the wrapper rather than adding NFC behavior to the self-owned flow.
$nfcStartText = "    // v11's restoreTiles uses render.call directly, bypassing G.a implementations."
$nfcEndText = '    function hookPanel(name, callback) {'
$nfcStart = $controls.IndexOf($nfcStartText)
$nfcEnd = $controls.IndexOf($nfcEndText)
if ($nfcStart -lt 0 -or $nfcEnd -le $nfcStart -or
    (Count-Text $controls $nfcStartText) -ne 1 -or (Count-Text $controls $nfcEndText) -ne 1) {
    throw 'capture-controls.js shared NFC compatibility block changed; update the deterministic assembler'
}
$controls = $controls.Remove($nfcStart, $nfcEnd - $nfcStart)

# Capture sources also run in the historical shared Hook, where logging is the
# existing contract. In this composite, initialization failures invalidate readiness.
$controlsFailure = "log('capture controls unavailable: ' + error);"
$indicatorFailure = "log('indicator unavailable: ' + error);"
$indicatorStartup = "log('startup: ' + error);"
foreach ($entry in @(@{Text=$controls; Needle=$controlsFailure}, @{Text=$indicator; Needle=$indicatorFailure}, @{Text=$indicator; Needle=$indicatorStartup})) {
    Require-Once $entry.Text $entry.Needle 'Capture failure reporting'
}
$report = "if (globalThis.__watchWorkshop && globalThis.__watchWorkshop.enabled('capture')) globalThis.__watchWorkshop.report('capture', error); "
$controls = $controls.Replace($controlsFailure, $report + $controlsFailure)
$indicator = $indicator.Replace($indicatorFailure, $report + $indicatorFailure).Replace($indicatorStartup, $report + $indicatorStartup)
Require-Once $base "codex_monet_enabled" 'Monet gate'
Require-Once $base $runtimeThemeJar 'Theme helper path'
Require-Once $widget "codex_widgets_enabled" 'Widget gate documentation'
Require-Once $widget "Registry.a.overload('java.lang.String')" 'Widget registry admission'
Require-Once $widget "Java.choose('com.heytap.wearable.launcher.quickcenter.view.QuickCenterView'" 'Breeno lifecycle attachment'
Require-Once $controls "log('capture controls ready');" 'Capture controls initialization'
Require-Once $indicator "log('native indicator ready');" 'Capture indicator initialization'

$sources = @(
    @{ Name = 'standalone/runtime-base.js'; Text = $base },
    @{ Name = 'standalone/widget-host.js'; Text = $widget },
    @{ Name = 'widget-host/capture-controls.js'; Text = $controls },
    @{ Name = 'widget-host/capture-indicator.js'; Text = $indicator }
)
$header = @(
    '// GENERATED by standalone/build-runtime.ps1. Do not edit by hand.',
    '// Composite order: runtime core/Monet, widget host, capture controls, capture indicator.',
    '// Sources:'
) + ($sources | ForEach-Object { '//   ' + $_.Name + '  sha256=' + (Get-Sha256 $_.Text) })
$trailer = @'
// Bootstrap commit: every module above has registered its hooks once. The marker
// is the new-user flow's initialization evidence after the single Launcher restart.
Java.perform(function () {
  Java.scheduleOnMainThread(function () {
  try {
    const runtime = globalThis.__watchWorkshop;
    if (!runtime) throw new Error('runtime coordinator missing');
    runtime.commit();
  } catch (error) {
    try {
      const base = globalThis.WatchWorkshopRuntimeBase;
      if (base) base.writeBootstrapFailure(Java, error);
    } catch (_) {}
    try { Java.use('android.util.Log').e('WatchWorkshopRuntime', String(error)); } catch (_) {}
  }
  });
});
'@

$output = (($header + @('') + @($base, $widget, $controls, $indicator, $trailer)) -join "`n")
$output = $output.TrimEnd("`n") + "`n"
$hash = Get-Sha256 $output
$expectedBytes = (New-Object Text.UTF8Encoding($false)).GetBytes($output)

if ($Check) {
    if (-not (Test-Path -LiteralPath $outputPath -PathType Leaf)) {
        throw "runtime-hook.js is missing; run build-runtime.ps1"
    }
    $actualBytes = [IO.File]::ReadAllBytes($outputPath)
    if (-not (Test-SameBytes $expectedBytes $actualBytes)) {
        throw "runtime-hook.js is stale or modified; rebuilt sha256=$hash"
    }
    Write-Host "runtime-hook.js verified sha256=$hash"
    return
}

[IO.File]::WriteAllText($outputPath, $output, (New-Object Text.UTF8Encoding($false)))
if (-not (Test-SameBytes $expectedBytes ([IO.File]::ReadAllBytes($outputPath)))) {
    throw 'runtime-hook.js byte check failed after write'
}
Write-Host "wrote runtime-hook.js sha256=$hash"
